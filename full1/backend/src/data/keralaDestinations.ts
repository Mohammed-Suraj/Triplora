const images = destinationImages as Record<string, { image: string; gallery: string[] }>;

function withImages<T extends { slug: string }>(dest: T): T & { image: string; gallery: string[] } {
  const imgs = images[dest.slug];
  if (imgs && imgs.image) {
    return { ...dest, image: imgs.image, gallery: imgs.gallery.length ? imgs.gallery : [imgs.image] };
  }
  // Fallback should never happen if the image fetch completed; keeps seed robust.
  return { ...dest, image: '/images/munnar.png', gallery: ['/images/munnar.png'] };
}

